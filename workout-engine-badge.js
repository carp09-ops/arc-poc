import { createClient } from 'https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.116.0/+esm';

const SUPABASE_URL = 'https://svxbzkjxihcwsbyheyxd.supabase.co';
const SUPABASE_PUBLISHABLE_KEY = 'sb_publishable_zm65KCzkWFvVmlnv9dpWFg_15L0nUfc';
const supabase = createClient(SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY, {
  auth: { persistSession: true, autoRefreshToken: true, detectSessionInUrl: false }
});

let refreshTimer = null;
let lastSetId = null;

function removeBadge() {
  document.getElementById('workoutEngineSource')?.remove();
}

function renderBadge(row) {
  const summary = document.getElementById('recommendationSummary');
  const options = document.getElementById('workoutOptions');
  if (!summary || !options || options.classList.contains('hidden') || !row) {
    removeBadge();
    return;
  }

  const mode = row.context_snapshot?.generation_mode;
  const ai = mode === 'ai' || String(row.generator_version || '').startsWith('openai-');
  const badge = document.getElementById('workoutEngineSource') || document.createElement('span');
  badge.id = 'workoutEngineSource';
  badge.className = `workout-engine-source ${ai ? 'ai' : 'safe'}`;
  badge.textContent = ai ? 'Arc AI' : 'Arc Safe Mode';
  badge.title = ai
    ? 'These workout options were generated by Arc’s AI workout engine.'
    : 'Arc used its deterministic safety fallback for these workout options.';

  if (!badge.isConnected) summary.insertAdjacentElement('afterend', badge);
}

async function refreshBadge() {
  clearTimeout(refreshTimer);
  const options = document.getElementById('workoutOptions');
  if (!options || options.classList.contains('hidden') || !options.children.length) {
    removeBadge();
    return;
  }

  try {
    const { data: auth } = await supabase.auth.getUser();
    if (!auth?.user) return;
    const { data, error } = await supabase
      .from('workout_recommendation_sets')
      .select('id,generator_version,generated_at,context_snapshot')
      .eq('user_id', auth.user.id)
      .order('generated_at', { ascending: false })
      .limit(1)
      .maybeSingle();
    if (error || !data) return;

    // Avoid attaching an old source label to stale DOM after a navigation race.
    const ageMs = Date.now() - new Date(data.generated_at).getTime();
    if (ageMs > 30 * 60 * 1000 && data.id === lastSetId) return;
    lastSetId = data.id;
    renderBadge(data);
  } catch (_) {
    // Source transparency is an enhancement; recommendations remain usable if it cannot render.
  }
}

function scheduleRefresh() {
  clearTimeout(refreshTimer);
  refreshTimer = setTimeout(refreshBadge, 180);
}

const observer = new MutationObserver(scheduleRefresh);
observer.observe(document.documentElement, { subtree: true, childList: true, attributes: true, attributeFilter: ['class'] });

window.addEventListener('DOMContentLoaded', scheduleRefresh);
window.addEventListener('pageshow', scheduleRefresh);
supabase.auth.onAuthStateChange((_event, session) => {
  if (session?.user) scheduleRefresh();
  else removeBadge();
});
